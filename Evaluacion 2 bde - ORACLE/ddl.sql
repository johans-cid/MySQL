CREATE TABLE regiones(
    IDREG NUMBER GENERATED ALWAYS AS IDENTITY, 
    NOMREG VARCHAR2(20) NOT NULL,

    CONSTRAINT pk_regiones PRIMARY KEY (IDREG)
);

CREATE TABLE sucursales(
    IDSUC NUMBER GENERATED ALWAYS AS IDENTITY,
    NOMSUC VARCHAR2(20) NOT NULL,

    CONSTRAINT pk_sucursales PRIMARY KEY (IDSUC)
);

CREATE TABLE rubros(
    IDRUB NUMBER GENERATED ALWAYS AS IDENTITY,
    NOMRUB VARCHAR2(20) NOT NULL,

    CONSTRAINT pk_rubros PRIMARY KEY (IDRUB)
);

CREATE TABLE ciudades(
    IDCIU NUMBER GENERATED ALWAYS AS IDENTITY,
    NOMCIU VARCHAR2(20) NOT NULL,
    FKIDREG NUMBER NOT NULL,

    CONSTRAINT pk_ciudades PRIMARY KEY (IDCIU),
    CONSTRAINT fk_ciudades_regiones FOREIGN KEY (FKIDREG) REFERENCES regiones(IDREG)
);

CREATE TABLE productos(
    IDPROD NUMBER GENERATED ALWAYS AS IDENTITY,
    NOMART VARCHAR2(30) NOT NULL,
    PRECIO NUMBER NOT NULL,
    FKIDRUB NUMBER NOT NULL,

    CONSTRAINT pk_productos PRIMARY KEY (IDPROD),
    CONSTRAINT fk_productos_rubros FOREIGN KEY (FKIDRUB) REFERENCES rubros(IDRUB)
);

CREATE TABLE clientes(
    IDRUT NUMBER,
    NOMCLI VARCHAR2(18) NOT NULL,
    APEPAT VARCHAR2(18) NOT NULL,
    APEMAT VARCHAR2(18),
    DIRECC VARCHAR2(30) NOT NULL,
    FKIDCIU NUMBER NOT NULL,

    CONSTRAINT pk_clientes PRIMARY KEY (IDRUT),
    CONSTRAINT fk_clientes_ciudad FOREIGN KEY (FKIDCIU) REFERENCES ciudades(IDCIU)
);

CREATE TABLE ventas(
    IDVENTA NUMBER GENERATED ALWAYS AS IDENTITY,
    FECHA DATE NOT NULL,
    FKIDSUC NUMBER NOT NULL,
    FKIDRUT NUMBER NOT NULL,
    TOTAL NUMBER,

    CONSTRAINT pk_ventas PRIMARY KEY (IDVENTA),
    CONSTRAINT fk_ventas_sucursales FOREIGN KEY (FKIDSUC) REFERENCES sucursales(IDSUC),
    CONSTRAINT fk_ventas_clientes FOREIGN KEY (FKIDRUT) REFERENCES clientes(IDRUT)
);

CREATE TABLE detalleventas(
    IDDET NUMBER GENERATED ALWAYS AS IDENTITY,
    CANTIDAD NUMBER NOT NULL,
    VALOR NUMBER NOT NULL,
    SUBTOTAL NUMBER NOT NULL,
    TOTAL NUMBER NOT NULL,
    FKIDVENTA NUMBER NOT NULL,
    FKIDPROD NUMBER NOT NULL,

    CONSTRAINT pk_detalleventas PRIMARY KEY (IDDET),
    CONSTRAINT fk_detalleventas_ventas FOREIGN KEY (FKIDVENTA) REFERENCES ventas(IDVENTA),
    CONSTRAINT fk_detalleventas_productos FOREIGN KEY (FKIDPROD) REFERENCES productos(IDPROD)
);