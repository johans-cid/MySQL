CREATE SEQUENCE seq_formapago START WITH 1 INCREMENT BY 1;
CREATE SEQUENCE seq_servicios START WITH 1 INCREMENT BY 1;
CREATE SEQUENCE seq_ciudades START WITH 1 INCREMENT BY 1;
CREATE SEQUENCE seq_tipocliente START WITH 1 INCREMENT BY 1;
CREATE SEQUENCE seq_clientes START WITH 1 INCREMENT BY 1;
CREATE SEQUENCE seq_pagos START WITH 1 INCREMENT BY 1;

