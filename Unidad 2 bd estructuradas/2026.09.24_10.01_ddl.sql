CREATE DATABASE oracle_live_sql;

USE oracle_live_sql;

-- Lo de arriba el use y el create lo hize en xxamp esta creada, lo de abajo esta en oracle cloud con otra sintaxis
-- (especificamente cambie el AUTO_INCREMENT por GENERATED AS IDENTITY)

CREATE TABLE IF NOT EXISTS regiones(
	IDREG INT GENERATED AS IDENTITY,
	NOMREG VARCHAR(20) NOT NULL,

	CONSTRAINT pk_regiones PRIMARY KEY (IDREG)
);

CREATE TABLE IF NOT EXISTS carreras(
	IDCAR INT GENERATED AS IDENTITY,
	NOMCAR VARCHAR(20) NOT NULL,
	VALORANUAL INT NOT NULL,
	
	CONSTRAINT pk_carreras PRIMARY KEY (IDCAR)
);

CREATE TABLE IF NOT EXISTS ciudades(
	IDCIU INT GENERATED AS IDENTITY,
	NOMCIU VARCHAR(20) NOT NULL,
	FK_ID_REGIONES INT NOT NULL,
	
	CONSTRAINT pk_ciudades PRIMARY KEY (IDCIU),
	CONSTRAINT fk_ciudades_regiones FOREIGN KEY (FK_ID_REGIONES) REFERENCES regiones(IDREG)
);

CREATE TABLE IF NOT EXISTS estudiantes(
	RUT INT,
	NOM VARCHAR(20) NOT NULL,
	APEP VARCHAR(20) NOT NULL,
	APEM VARCHAR(20),
	DIRECC VARCHAR(30) NOT NULL,
	FK_ID_CARRERAS INT NOT NULL,
	FK_ID_CIUDADES INT NOT NULL,
	CONSTRAINT pk_estudiantes PRIMARY KEY (RUT),
	CONSTRAINT fk_estudiantes_carreras FOREIGN KEY (FK_ID_CARRERAS) REFERENCES carreras(IDCAR),
	CONSTRAINT fk_estudiantes_ciudades FOREIGN KEY (FK_ID_CIUDADES) REFERENCES ciudades(IDCIU)
	
);